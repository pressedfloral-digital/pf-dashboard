-- Pre-dashboard ratio history, backfilled from each location's master-
-- calculations Google Sheet ("UTAH 2024-2026 PF Master Calculations_New_Ready"
-- and "GEORGIA 2024-2026 PF Master Calculations_New_Ready"), one
-- "<Dept> - Detail" tab per department. Covers W/C 2024-01-01 through W/C
-- 2025-12-22 -- every week before team_member_week_actuals begin (W/C
-- 2025-12-29). Like cpo_sheet_backfill, /api/kpis only reads a location-week
-- from here when the dashboard has no labor or actuals rows of its own for it.
--
-- ratio_hours / ratio_production = the tab's total hours and total production
-- minus every manager's hours AND production, matching how the dashboard
-- excludes managers from the ratio. Not the sheet's own "Ratio: Actual" as-is:
-- its formula sometimes dropped a manager's hours but kept their production,
-- and stopped excluding salaried managers who logged production with no
-- clocked hours. A person counts as a manager for a week if any of:
--   * they're isManager on that location/dept's current schedule roster
--     (exactly the dashboard's rule, applied to every week),
--   * the sheet's ratio formula excluded them that week (hours or production),
--   * the sheet excluded them in other weeks, and this week they have
--     production but no clocked hours (salaried).
-- Former managers stay in for weeks they clocked hours and the sheet counted
-- them as team (before a promotion / after stepping down).
--
-- Resin (Utah only, from W/C 2025-08-11) uses its tab's "Total ... without
-- manager" rows, which exclude Audrey Brown from both.
--
-- Known sheet issue: Utah Fulfillment W/C 2025-05-26 has a hand-entered
-- production total (155) with only 3 attributed to anyone, so its ratio
-- (~0.13) is an outlier; kept as the sheet has it.
--
-- A separate table from cpo_sheet_backfill because it reaches further back
-- (the cost sheet starts W/C 2025-08-11) and comes from different sheets.
