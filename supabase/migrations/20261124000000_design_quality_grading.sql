-- Weekly Design Quality grading (replaces the per-week "Design Quality
-- Metric Rubric" Google Sheet). Each week, a manager hits "Pick this week's
-- frames": every designer who had a frame first reach No Response
-- (frameCompleted) that week gets 1–3 frames picked at random, by hours worked
-- (<20 → 1, 20–30 → 2, 30+ → 3). The grader then scores each picked frame
-- against the 23-point rubric (src/lib/designQualityRubric.ts).

-- One row per designer per week: who is being graded and how many frames.
create table if not exists design_quality_designers (
  id                 bigint generated by default as identity primary key,
  week_of            date not null,              -- Monday of the graded week
  designer_name      text not null,              -- canonical (roster/Rippling) name
  location           text,                       -- 'Utah' | 'Georgia' | null if unknown
  hours              numeric,                    -- total hours worked that week (null = no hours uploaded)
  frames_available   integer not null default 0, -- frames that first hit No Response that week
  candidate_frames   jsonb not null default '[]'::jsonb, -- those frames, for re-picking without re-scanning the API
  target_count       integer not null,           -- frames to grade
  excluded           boolean not null default false,
  created_by         text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  unique (week_of, designer_name)
);

-- One row per frame picked for grading.
create table if not exists design_quality_pieces (
  id                    bigint generated by default as identity primary key,
  designer_id           bigint not null references design_quality_designers(id) on delete cascade,
  week_of               date not null,
  slot                  integer not null,          -- 1, 2, 3 (Piece 1 / 2 / 3)
  order_num             text not null,
  order_product_uuid    text not null,
  variant_title         text,
  first_no_response_at  timestamptz not null,
  rubric_version        text not null default 'v23',
  scores                jsonb not null default '{}'::jsonb,  -- { criterionKey: 0 | 0.5 | 1 }
  criterion_notes       jsonb not null default '{}'::jsonb,  -- { criterionKey: "note" }
  notes                 text,                                -- overall notes for the piece
  seconds_spent         integer not null default 0,          -- time the grader had the piece open
  completed_at          timestamptz,                         -- null until marked graded
  graded_by             text,                                -- Clerk user id
  graded_by_name        text,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  unique (designer_id, slot),
  unique (week_of, order_product_uuid)
);

create index if not exists design_quality_designers_week_idx on design_quality_designers (week_of);
create index if not exists design_quality_pieces_week_idx on design_quality_pieces (week_of);

-- Server-only, like every other dashboard table (see
-- 20261027223000_restrict_dashboard_data_api.sql).
alter table design_quality_designers enable row level security;
alter table design_quality_pieces enable row level security;
revoke all on design_quality_designers, design_quality_pieces from public, anon, authenticated;
